/// Terminal output: a summary table, then findings grouped by check. Long
/// groups are truncated unless [verbose].
String renderHuman(
  Analysis analysis,
  List<Finding> fresh,
  List<Finding> known, {
  bool colour = false,
  bool verbose = false,
  int perCheckLimit = 15,
}) {
  String c(String code, String s) => colour ? '\x1B[${code}m$s\x1B[0m' : s;
  String sev(Severity s) => switch (s) {
    Severity.error => c('31;1', 'error'),
    Severity.warning => c('33', 'warn '),
    Severity.info => c('36', 'info '),
  };

  final out = StringBuffer();
  final stats = analysis.stats;
  out.writeln(
    c('1', 'l10n_health') +
        c(
          '2',
          '  ${stats.generator} · template ${stats.templateLocale} · '
              '${stats.keys} keys · ${stats.dartFiles} Dart files · '
              '${stats.usageMode.name} usage · ${stats.elapsed.inMilliseconds} ms',
        ),
  );
  out.writeln();

  final locales = stats.locales.entries
      .map((e) => '${e.key} ${e.value}')
      .join('  ');
  out.writeln('  Locales   $locales');
  out.writeln();

  final grouped = byCheck(fresh);
  if (grouped.isEmpty) {
    out.writeln(c('32', '  No new findings.'));
  }
  for (final MapEntry(key: check, value: list) in grouped.entries) {
    out.writeln(
      '${c('1', checkTitle(check))} ${c('2', '($check)')}  '
      '${c('1', '${list.length}')}',
    );
    if (perCheckLimit == 0 && !verbose) continue;
    final shown = verbose ? list : list.take(perCheckLimit);
    for (final f in shown) {
      out.writeln(
        '  ${sev(f.severity)} ${c('2', '${f.file}:${f.line}:${f.column}')}  '
        '${f.message}',
      );
    }
    if (!verbose && list.length > perCheckLimit) {
      out.writeln(
        c(
          '2',
          '  … ${list.length - perCheckLimit} more (use --verbose '
              'or --format html)',
        ),
      );
    }
    out.writeln();
  }

  final counts = severityCounts(fresh);
  out.write(
    '${counts[Severity.error]} errors, ${counts[Severity.warning]} warnings, '
    '${counts[Severity.info]} info',
  );
  if (known.isNotEmpty) out.write(' · ${known.length} in baseline');
  out.writeln();
  return out.toString();
}

String renderJson(Analysis analysis, List<Finding> fresh, List<Finding> known) {
  return '${const JsonEncoder.withIndent('  ').convert({
    'tool': 'l10n_health',
    'stats': analysis.stats.toJson(),
    'summary': {for (final e in byCheck(fresh).entries) e.key: e.value.length},
    'findings': [for (final f in fresh) f.toJson()],
    'baselined': known.length,
  })}\n';
}

/// Markdown, for merge-request comments and wiki pages. Locations are
/// relative links resolved from wherever the file is written.
String renderMarkdown(
  Analysis analysis,
  List<Finding> fresh,
  List<Finding> known, {
  required String projectName,
  String linkPrefix = '',
  int perCheckLimit = 200,
}) {
  final out = StringBuffer();
  final stats = analysis.stats;
  final counts = severityCounts(fresh);
  out
    ..writeln('# l10n health: $projectName')
    ..writeln()
    ..writeln(
      '${counts[Severity.error]} errors · ${counts[Severity.warning]} '
      'warnings · ${counts[Severity.info]} info'
      '${known.isEmpty ? '' : ' · ${known.length} baselined'}',
    )
    ..writeln()
    ..writeln('| Locale | Keys | Missing |')
    ..writeln('|---|---:|---:|');
  final missing = fresh.where((f) => f.check == 'missing_translation');
  for (final MapEntry(key: locale, value: n) in stats.locales.entries) {
    final m = missing.where((f) => f.locale == locale).length;
    final mark = locale == stats.templateLocale ? ' (template)' : '';
    out.writeln('| `$locale`$mark | $n | $m |');
  }
  out
    ..writeln()
    ..writeln('| Check | Findings |')
    ..writeln('|---|---:|');
  final grouped = byCheck(fresh);
  for (final MapEntry(key: check, value: list) in grouped.entries) {
    out.writeln('| ${checkTitle(check)} (`$check`) | ${list.length} |');
  }
  out.writeln();

  for (final MapEntry(key: check, value: list) in grouped.entries) {
    out
      ..writeln('## ${checkTitle(check)} (${list.length})')
      ..writeln()
      ..writeln('_${checkWhy(check)}_')
      ..writeln();
    for (final f in list.take(perCheckLimit)) {
      final loc = '${f.file}:${f.line}';
      out.writeln(
        '- [`$loc`]($linkPrefix${f.file}#L${f.line}) '
        '${_mdEscape(f.message)}',
      );
    }
    if (list.length > perCheckLimit) {
      out.writeln('- … and ${list.length - perCheckLimit} more');
    }
    out.writeln();
  }

  out.writeln(
    '<sub>Generated by l10n_health in ${stats.elapsed.inMilliseconds} ms '
    '· ${stats.keys} keys · ${stats.dartFiles} Dart files · '
    '${stats.usageMode.name} usage detection</sub>',
  );
  return out.toString();
}

String _mdEscape(String s) =>
    s.replaceAll('|', r'\|').replaceAll('<', '&lt;').replaceAll('\n', ' ');

/// GitLab Code Quality JSON, for merge-request widgets.
String renderGitLab(List<Finding> fresh) {
  final issues = [
    for (final f in fresh)
      {
        'description': '${f.check}: ${f.message}',
        'check_name': f.check,
        'fingerprint': f.fingerprint,
        'severity': switch (f.severity) {
          Severity.error => 'critical',
          Severity.warning => 'major',
          Severity.info => 'info',
        },
        'location': {
          'path': f.file,
          'lines': {'begin': f.line},
        },
      },
  ];
  return '${const JsonEncoder.withIndent('  ').convert(issues)}\n';
}

/// GitHub Actions workflow commands: findings appear as annotations on the
/// pull request diff.
String renderGitHub(List<Finding> fresh) {
  String esc(String s) =>
      s.replaceAll('%', '%25').replaceAll('\r', '%0D').replaceAll('\n', '%0A');
  final out = StringBuffer();
  for (final f in fresh) {
    final level = switch (f.severity) {
      Severity.error => 'error',
      Severity.warning => 'warning',
      Severity.info => 'notice',
    };
    out.writeln(
      '::$level file=${f.file},line=${f.line},col=${f.column},'
      'title=${f.check}::${esc(f.message)}',
    );
  }
  return out.toString();
}
